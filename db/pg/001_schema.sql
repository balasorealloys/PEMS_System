-- updated_at triggers on every table that carries the column ------------------
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'pems_cost_center','pems_load','pems_load_feeder_map','pems_tariff',
    'pems_config','pems_constant','pems_meter_factor','pems_user_role','pems_rollup_state'
  ] LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS trg_%1$s_updated ON pems.%1$s', t);
    EXECUTE format('CREATE TRIGGER trg_%1$s_updated BEFORE UPDATE ON pems.%1$s '
                   'FOR EACH ROW EXECUTE FUNCTION pems.set_updated_at()', t);
  END LOOP;
END $$;
