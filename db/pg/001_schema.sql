-- PEMS schema for PostgreSQL 16 (target: corpappdb, schema "pems").
-- Consolidated equivalent of the MySQL migrations 001–012 (all ALTERs folded in),
-- ported to Postgres: NUMERIC for DECIMAL, BOOLEAN for TINYINT(1), TIMESTAMP for
-- DATETIME, JSONB for JSON, IDENTITY for AUTO_INCREMENT, and an updated_at trigger
-- in place of MySQL's "ON UPDATE CURRENT_TIMESTAMP".
--
-- The raw meter table pems.em_valuedata_ci1001 is synced externally and already
-- present — this file never touches it. Run once against corpappdb as a role that
-- can create objects in schema "pems".

SET search_path TO pems;

-- updated_at auto-touch (replaces MySQL's ON UPDATE CURRENT_TIMESTAMP) -----------
CREATE OR REPLACE FUNCTION pems.set_updated_at() RETURNS trigger AS $$
BEGIN NEW.updated_at = now(); RETURN NEW; END;
$$ LANGUAGE plpgsql;

